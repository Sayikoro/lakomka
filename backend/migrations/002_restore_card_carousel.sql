-- Задача 83 (регресс галереи в карточках товаров).
--
-- Симптом: в каталоге пропала галерея «клик по картинке — переключение
-- слайда». Причина: админ-форма настроек при отсутствии ключа в БД
-- подставляла дефолт «classic» и сохраняла его при ЛЮБОМ сохранении
-- настроек (включение снегопада, SMTP и т.п.) — каталог переключался
-- на старую карточку без карусели.
--
-- Лечение: дефолт формы исправлен на «new» в коде; эта миграция один
-- раз возвращает карусель («new») на уже работающих сайтах, где
-- «classic» успел записаться в базу. Если владелец позже сознательно
-- выберет классический шаблон в админке — его выбор сохранится
-- (миграция применяется только один раз).
--
-- Индемпотентно: upsert по первичному ключу.

INSERT INTO settings (key, value) VALUES ('product_card_template', 'new')
  ON CONFLICT(key) DO UPDATE SET value = excluded.value;
