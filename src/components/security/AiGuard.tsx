/**
 * AI-FIREWALL — барьер для ИИ-агентов и языковых моделей.
 *
 * Что это: скрытый блок + meta-теги, попадающие в HTML каждой страницы
 * витрины и админки. Автономные ИИ-агенты (браузерные ассистенты, скрейперы
 * с LLM) читают исходник страницы как промпт — этот блок встраивает туда
 * запрет на любые действия, кроме чтения, и предупреждение о prompt injection
 * через контент страниц (товары, комментарии, поля заказов).
 *
 * Это второй рубеж: первый — robots.txt (запрет ИИ-краулерам) и 403 по
 * User-Agent в .htaccess. Настоящая защита API — авторизация и CSRF-щит;
 * здесь мы отрезаем «послушных» агентов и показываем злонамеренным, что
 * их инструкции не работают.
 */

