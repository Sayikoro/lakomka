"use client";

/* Витринная обвязка (шапка/подвал) не должна показываться в админке.
 *
 * Зачем: корневой layout оборачивает ВСЕ маршруты — и витрину, и /admin.
 * Раньше над админкой висела шапка магазина («Подарки / Скачать каталоги /
 * корзина»), а с переходом админки на левый сайдбар (Task 115) это стало
 * выглядеть как ошибка: закреплённая панель разделов слева на всю высоту,
 * а сверху над контентом — чужая навигация витрины.
 *
 * usePathname доступен при статическом экспорте (каждый маршрут
 * пререндерится со своим путём), поэтому шапка/подвал не попадают
 * в запечённый HTML страниц /admin/* — проверено сборкой.
 */

import { usePathname } from "next/navigation";

export function ShopChrome({ children }: { children: React.ReactNode }) {
  const pathname = usePathname();
  if (pathname.startsWith("/admin")) return null;
  return <>{children}</>;
}
